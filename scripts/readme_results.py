#!/usr/bin/env python3
"""Splice results/*.txt into README.md between the RESULTS markers (nothing typed by hand; a missing file becomes NOT YET MEASURED)."""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def part(title, f, cmd, n=None):
    p = os.path.join(ROOT, "results", f)
    if not os.path.exists(p):
        return "### %s\n\nNOT YET MEASURED - run `%s`.\n" % (title, cmd)
    t = open(p).read().rstrip("\n")
    if n:
        t = "\n".join(t.splitlines()[:n])
    return "### %s\n\nFrom `results/%s` (`%s`).\n\n```text\n%s\n```\n" % (title, f, cmd, t)


blocks = [part("UVM runs", "uvm_runs.txt", "scripts/run_uvm.sh + scripts/run_summary.py"),
          part("Functional coverage, WIDTH = 8 (exhaustive)", "coverage_w8.txt", "scripts/cov_uvm.py build/w8/coverage.dat"),
          part("Functional coverage, WIDTH = 16 (random_seq_vl)", "coverage_w16.txt", "scripts/cov_uvm.py build/w16/coverage.dat"),
          part("Injected bugs vs the original environment", "mutants.txt", "scripts/mutate_alu.py", n=8),
          part("Injected bugs vs original + ext/uvm_ext.sv", "mutants_ext.txt", "scripts/mutate_alu.py --with-ext", n=8)]
new = ("<!-- BEGIN RESULTS (generated by scripts/readme_results.py from results/; do not edit by hand) -->\n\n"
       + "\n".join(blocks) + "\n<!-- END RESULTS -->")
p = os.path.join(ROOT, "README.md")
old = open(p).read()   # read BEFORE opening for write (open(p, "w") truncates)
open(p, "w").write(re.sub(r"<!-- BEGIN RESULTS.*?<!-- END RESULTS -->", lambda m: new, old, flags=re.S))
print("README results block updated")
